def item_name(i):
    for key in ("ITEM_" + i.upper(), "BUILDING_" + i.upper(), "FLUID_" + i.upper()):
        if key in names:
            return names[key]
    return i


def building_name(b):
    return names.get("BUILDING_" + b.upper(), b)


def fmt(v):
    if isinstance(v, float):
        return ("%.2f" % v).rstrip("0").rstrip(".")
    return str(v)


def stacks(lst):
    return ", ".join("%s ×%s" % (item_name(i), fmt(a)) for i, a in lst) if lst else "—"


